/** Ícone do Phosphor (aceita `weight`: duotone, fill, regular, bold…) ou composto (ver `composite`). */
export type IconComponent = ComponentType<{ className?: string; weight?: IconWeight }>

/**
 * Ícone composto: o Phosphor não tem calendário com seta de download; este põe um ícone pequeno no
 * canto de outro (o selo com o fundo da superfície, para destacar do de baixo).
 */
function composite(Base: Icon, Badge: Icon): IconComponent {
  const Composite = ({ className = '', weight }: { className?: string; weight?: IconWeight }) =>
    createElement(
      'span',
      { className: `relative inline-block ${className}` },
      createElement(Base, { className: 'size-full', weight }),
      createElement(
        'span',
        { className: 'absolute -right-0.5 -bottom-0.5 inline-flex size-[55%] items-center justify-center rounded-full bg-surface' },
        createElement(Badge, { className: 'size-full', weight: 'bold' }),
      ),
    )
  return Composite
}

/** `current`: a escolha atual (marcada como "atual" e escolhida de início). */
type Option = { name: string; icon: IconComponent; note?: string; current?: boolean }

const ph = (icon: IconComponent, name: string, note?: string, current?: boolean): Option => ({
  name,
  icon,
  ...(note ? { note } : {}),
  ...(current ? { current } : {}),
})

