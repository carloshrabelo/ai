/** Ícone do Phosphor (aceita `weight`: duotone, fill, regular, bold…). */
export type IconComponent = Icon

/** `current`: a escolha atual (marcada como "atual" e escolhida de início). */
type Option = { name: string; icon: IconComponent; note?: string; current?: boolean }

const ph = (icon: IconComponent, name: string, note?: string, current?: boolean): Option => ({
  name,
  icon,
  ...(note ? { note } : {}),
  ...(current ? { current } : {}),
})

